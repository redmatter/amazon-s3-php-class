class VerifyPurgeApp extends BaseApp
{
    const CONF_SAMPLE = '/usr/share/archiving/archiving-verifypurge.conf.sample';

    /**
     * API Url and token
     *
     * @var array
     */
    private $_apiAuth;

    /**
     * Fields generated by this script in the CSV output
     *
     * @var array
     */
    private $_fields = array(
        'Identifier',
        'PolicyID',
        'PolicyVersion',
        'CreationDate',
        'RetentionMinDate',
        'RetentionMaxDate',
        'EndpointID',
        'PurgedByDate',
        'PurgedByPolicyVersion',
        'RetentionStateExpected',
        'RetentionStateFound',
        'StorageStateExpected',
        'StorageStateFound',
        'Result'
    );

    private $_internalFiletypeDeleted = false;

    /**
     * Authenticate to Core API using the details given
     *
     * @param string $coreapi   coreapi url
     * @param string $authCreds creds
     *
     * @return void
     *
     * @throws Exception
     */
    private function _coreApiAuthenticate($coreapi, $authCreds)
    {
        $authorization = null;

        if (strpos($authCreds, ' ') === false)
        {
            // no scheme specified, assume it's basic auth
            $authCreds = "Basic {$authCreds}";
        }
        $authHdrs = array('Authorization' => $authCreds);
        $authUrl = "{$coreapi}/auth";

        $stream = HTTPStream::Make('GET', $authUrl, null/*body*/, $authHdrs);
        if ($stream && $stream->httpCode == 201)
        {
            $xpath = new XPath($stream->getContents());
            $authorization = $xpath('/Success/ResourceID');
            LogVerbose('Authenticated');
        }

        if (!$authorization)
            throw new Exception('Failed to authenticate using the credentials given');

        $this->_apiAuth = array($coreapi, $authorization);
    }

    /**
     * Destructor
     *
     * Mainly to delete the auth token
     */
    public function __destruct()
    {
        if ($this->_apiAuth)
        {
            HTTPStream::Make('DELETE', "{$this->_apiAuth[0]}/auth", null, array('Authorization' =>$this->_apiAuth[1]));
            LogVerbose('Auth deleted', $this->_apiAuth);
        }
    }

    /**
     * Get db connection
     *
     * @param string $connector connection name
     *
     * @return MySQLiConnection
     */
    private function _getDatabaseConnection($connector)
    {
        if (!isset($this->dbc[$connector]))
        {
            $this->dbc[$connector] = MySQLiConnection::Get($connector);
        }

        return $this->dbc[$connector];
    }

    /**
     * override 'Purged' with 'RecordDeleted' for InternalFiletypes
     *
     * @param string $identifier              "filetype/orgId/UUID" form
     * @param string $purgeState              "Purged" or "Available"
     * @param bool   $internalFiletypeDeleted are they set to be deleted from CLI
     *
     * @return string
     */
    private static function _getRetentionDbPurgedState($identifier, $purgeState, $internalFiletypeDeleted)
    {
        $identifier = array_combine(array('Type', 'OrgID', 'UUID'), explode('/', $identifier));
        if ($purgeState === 'Purged' 
            && $internalFiletypeDeleted === true
            && Archiving::FileTypeIsInternalData(Archiving::GetFileType($identifier['Type'])))
        {
            return 'RecordDeleted';
        }

        return $purgeState;
    }

    /**
     * Get the current state of an object in archive
     *
     * @param string $identifier archive object identifier type/orgId/uuid
     * @param int    $endpointId endpoint where object was stored
     *
     * @return array
     * @throws Exception
     */
    private function _getCurrentState($identifier, $endpointId)
    {
        $identifier_str = $identifier;
        $identifier = array_combine(array('Type', 'OrgID', 'UUID'), explode('/', $identifier));

        $type = Archiving::GetFileType($identifier['Type']);
        $uuid_hex = str_replace('-', '', $identifier['UUID']);

        $res = $this->_getDatabaseConnection('retention_ro')->query(
            "SELECT `State`, `EndpointID` " .
            "FROM `ArchivingRetention`.`Retention_{$identifier['OrgID']}` " .
            "WHERE `Type`={$type} AND `UUID`=0x{$uuid_hex} " .
            "LIMIT 1"
        )->fetch_all(MySQLiResult::AS_ASSOC);
        if (empty($res))
        {
            if ($this->_internalFiletypeDeleted === true && Archiving::FileTypeIsInternalData($type))
            {
                $retentionStateFound = 'RecordDeleted';
            }
            else
            {
                throw new Exception("$identifier_str not found in Retention database");
            }
        }
        else
        {
            list($retentionStateFound, $endpointIdFound) = array_values(reset($res));
            if ($endpointIdFound != $endpointId)
            {
                throw new Exception("Endpoint-id for $identifier_str does not match");
            }
        }

        $endpoint = ArchivingEndpoint::Get($this->_apiAuth, $identifier['OrgID'], $endpointId, true);
        switch ($endpoint->type)
        {
            case 's3':
                $s3creds = new S3Credentials($endpoint->accessKey, $endpoint->secretKey);
                $s3endpoint = new S3EndpointConfig();
                break;
            case 's3-emulation':
                if (1 !== preg_match('/^([^\/]+)(.*)$/', $endpoint->baseURI, $matches))
                {
                    throw new Exception("Malformed BaseURI '{$endpoint->baseURI}' in storage endpoint");
                }
                $s3creds = new S3Credentials($endpoint->accessKey, $endpoint->secretKey);
                $s3endpoint = new S3EndpointConfig($matches[1], $endpoint->region);
                break;
            default:
                throw new Exception("Storage Endpoint Type '{$endpoint->type}' not supported");
                break;
        }

        $storageStateFound = S3::getObjectInfo($endpoint->bucket, $identifier_str, false, $s3endpoint, $s3creds) ? 'Available' : 'Purged';

        return array($retentionStateFound, $storageStateFound, $endpoint->retentionManaged);
    }

    /**
     * Check CSV file(s) for the given expected state
     *
     * @param string $csvFiles      CSV file paths to check; more than one can be specified as comma separated
     * @param string $expectedState 'Available' or 'Purged'
     * @param bool   $failFast      fail on first error?
     *
     * @return int number of failures
     *
     * @throws Exception
     */
    private function _checkCsvFiles($csvFiles, $expectedState, $failFast)
    {
        $failCount = 0;

        // split and trim file names / paths
        $csvFiles = array_map('trim', preg_split('/, */', $csvFiles));
        $fp = null;
        foreach ($csvFiles as $path)
        {
            if (!is_readable($path))
            {
                throw new Exception("$path - Not readable");
            }

            $sentry = new ScopeSentry(
                function () use (&$fp)
                {
                    if ($fp)
                    {
                        fclose($fp);
                        unset($fp);
                    }
                }
            );

            $fp = fopen($path, 'r');
            if (false === $fp)
            {
                throw new Exception("$path - Unable to open");
            }

            while ($line = fgetcsv($fp))
            {
                // skip the heading line
                if (0 === strpos($line[0], 'Type'))
                {
                    echo implode(",", $this->_fields)."\n";
                    continue;
                }

                // RetentionStateExpected (override 'Purged' with 'RecordDeleted' for InternalFiletypes)
                $line[] = self::_getRetentionDbPurgedState($line[0] /* Identifier */, $expectedState, $this->_internalFiletypeDeleted);
                // RetentionStateFound
                $line[] = null;
                // StorageStateExpected
                $line[] = $expectedState;
                // StorageStateFound
                $line[] = null;
                // Result
                $line[] = null;

                $row = array_combine($this->_fields, $line);

                list($row['RetentionStateFound'], $row['StorageStateFound'], $isRetentionManaged) =
                    $this->_getCurrentState($row['Identifier'], $row['EndpointID']);

                // Override "StorageStateExpected" based on what was found in endpoint config
                if (!$isRetentionManaged) {
                    $row['StorageStateExpected'] = 'Available';
                }

                $ok = $row['RetentionStateFound'] == $row['RetentionStateExpected']
                    && $row['StorageStateFound'] == $row['StorageStateExpected'];
                $row['Result'] = $ok? 'OK': 'Failed';

                echo implode(",", $row)."\n";

                if (!$ok)
                {
                    if ($failFast)
                    {
                        throw new Exception(
                            "{$row['Identifier']} found " .
                            "Retention:'{$row['RetentionStateFound']}' Storage:'{$row['StorageStateFound']}'"
                        );

                    }
                    $failCount++;
                }
            }
        }

        return $failCount;
    }

    /**
     * Runner
     *
     * @throws Exception
     *
     * @return void
     */
    public function run()
    {
        $config = $this->getConf();

        $this->_internalFiletypeDeleted = CLI::Get('--internal-filetypes-records-deleted', false);

        $authCreds = CLI::Get('--auth-creds', $config->get('api.authorization_creds', false));
        if (!$authCreds)
        {
            throw new Exception('No authorization creds or hash specified');
        }

        $coreapi = $config->get('api.base_url', 'http://api.redmatter.com');

        $this->_coreApiAuthenticate($coreapi, $authCreds);

        $failFast = CLI::Get('--fail-fast', false);
        $failCount = 0;

        $shouldBe = CLI::Get('--should-be-purged-csv', false);
        if (false !== $shouldBe)
        {
            $failCount += $this->_checkCsvFiles($shouldBe, 'Purged', $failFast);
        }

        $shouldNotBe = CLI::Get('--should-not-be-purged-csv', false);
        if (false !== $shouldNotBe)
        {
            $failCount += $this->_checkCsvFiles($shouldNotBe, 'Available', $failFast);
        }

        if ($failCount > 0)
        {
            throw new Exception("$failCount failure(s) found during verification");
        }
    }
}

